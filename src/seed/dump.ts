/**
 * Writes the generated seed data as plain SQL INSERT statements (bun run seed:sql > db/seed.sql),
 * so instructors and students can read the data set without running the server.
 */
import { generate } from './generate';
import { TABLES } from './index';

const lit = (v: unknown): string => {
  if (v === null || v === undefined) return 'NULL';
  if (v instanceof Date) return `'${v.toISOString()}'`;
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const ds = generate();
const out: string[] = ['-- Generated by src/seed/dump.ts. Do not edit by hand.', 'BEGIN;'];
for (const t of TABLES) {
  const rows = (ds as any)[t] as Record<string, unknown>[];
  if (!rows.length) continue;
  const cols = Object.keys(rows[0]);
  out.push(`\n-- ${t} (${rows.length})`);
  for (const r of rows) out.push(`INSERT INTO ${t} (${cols.join(', ')}) VALUES (${cols.map((c) => lit(r[c])).join(', ')});`);
}
for (const [seq, value] of Object.entries(ds.sequences)) out.push(`SELECT setval('${seq}', ${value}, true);`);
out.push('COMMIT;');
console.log(out.join('\n'));
